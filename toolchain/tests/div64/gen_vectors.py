#!/usr/bin/env python3
# Generate reference vectors for div64test.c: 64-bit unsigned and signed
# division and remainder computed by Python (C semantics: truncation toward
# zero, remainder has the sign of the dividend).  Deterministic (seeded).
import random

M = 1 << 64
random.seed(1802)
edge = [0, 1, 2, 3, 7, 10, 1000000, 1000000000, 0x7fffffff, 0x80000000,
        0xffffffff, 0x100000000, 0x123456789, 0x7fffffffffffffff,
        0x8000000000000000, 0xffffffffffffffff, 0xfffffffffffffffe]
pairs = [(a, b) for a in edge for b in edge if b != 0]
# Around the 16-bit fast path of udivmod64 (both operands < 0x10000)
edge16 = [0, 1, 7, 10, 0xff, 0x100, 0x7fff, 0x8000, 0xfffe, 0xffff, 0x10000,
          0x10001, 655350]
pairs += [(a, b) for a in edge16 for b in edge16 if b != 0]
for _ in range(220):
    a = random.getrandbits(random.randint(1, 64))
    b = random.getrandbits(random.randint(1, 64)) or 1
    pairs.append((a, b))


def s(x):
    return x - M if x >= 1 << 63 else x


def cdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


print("/* generated by gen_vectors.py: n, d, n/d, n%%d (unsigned), "
      "n/d, n%%d (signed) */")
print("static const struct vec g_vec[] =\n{")
for a, b in pairs:
    sa, sb = s(a), s(b)
    if sa == -(1 << 63) and sb == -1:
        sq, sr = 0, 0            # overflow: not checked (flag = 0)
        chk = 0
    else:
        sq = cdiv(sa, sb)
        sr = sa - sq * sb
        chk = 1
    print("  { 0x%016xULL, 0x%016xULL, 0x%016xULL, 0x%016xULL, "
          "0x%016xULL, 0x%016xULL, %d }," %
          (a, b, a // b, a % b, sq % M, sr % M, chk))
print("};")
