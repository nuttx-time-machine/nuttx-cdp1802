#!/usr/bin/env python3
# toolchain/tests/inline/gen.py <out.c> <expected.txt>
#
# Test for the GCC options -minline-calls, -minline-compare and
# -minline-shifts (ADR 0023).  Generates a C program that prints, as text,
# the result of every 16-bit comparison code on pairs of edge values
# (register-register and register-constant), of every constant shift
# count for <<, >> (unsigned) and >> (signed), and of calls with stack
# arguments, recursion and varargs.  The expected output is computed here
# in Python, so a miscompiled comparison inside the program cannot hide its
# own failure: the test script compares the two texts.
import sys

V = [0x0000, 0x0001, 0x0002, 0x007f, 0x0080, 0x00ff, 0x0100, 0x0101,
     0x7ffe, 0x7fff, 0x8000, 0x8001, 0xfffe, 0xffff, 0x1234, 0xedcb,
     0xff00, 0xff80, 0x0180, 0x8080]
K = [0x0000, 0x0001, 0xffff, 0x7fff, 0x8000, 0x0080, 0x00ff, 0x0100,
     0x0011, 0x012c, 0xfed4, 0x1234, 0x8080, 0x00fe]
OPS = [("eq", "==", "int"), ("ne", "!=", "int"), ("lt", "<", "int"),
       ("le", "<=", "int"), ("gt", ">", "int"), ("ge", ">=", "int"),
       ("ltu", "<", "unsigned int"), ("leu", "<=", "unsigned int"),
       ("gtu", ">", "unsigned int"), ("geu", ">=", "unsigned int")]


def s16(x):
    return x - 0x10000 if x & 0x8000 else x


def pyop(op, a, b, typ):
    if typ == "int":
        a, b = s16(a), s16(b)
    return int({"==": a == b, "!=": a != b, "<": a < b, "<=": a <= b,
                ">": a > b, ">=": a >= b}[op])


def cconst(k, typ):
    return "(%s)0x%04xu" % (typ, k)


def main():
    c, exp = [], []
    w = c.append
    w("/* Generated by gen.py: do not edit. */")
    w("#include <stdio.h>")
    w("#include <stdarg.h>")
    w("#define NI __attribute__((noinline, noclone))")
    w("static const unsigned int v[%d] = {%s};" %
      (len(V), ", ".join("0x%04x" % x for x in V)))
    w("static int col;")
    w("static void out(int ch) { putchar(ch); if (++col == 64) "
      "{ putchar('\\n'); col = 0; } }")
    w("static void end(void) { if (col) putchar('\\n'); col = 0; }")
    w("static const char hex[] = \"0123456789abcdef\";")
    w("static void outx(unsigned int x) { out(hex[(x >> 12) & 15]); "
      "out(hex[(x >> 8) & 15]); out(hex[(x >> 4) & 15]); out(hex[x & 15]); }")
    lines = []

    def emit(s):
        # expected output: characters in lines of 64
        lines.append(s)

    # register-register comparisons
    for name, op, typ in OPS:
        w("NI static int rr_%s(%s a, %s b) { if (a %s b) return 1; "
          "return 0; }" % (name, typ, typ, op))
    for name, op, typ in OPS:
        for k in K:
            w("NI static int rc_%s_%04x(%s a) { if (a %s %s) return 1; "
              "return 0; }" % (name, k, typ, op, cconst(k, typ)))
    shifts = [("shl", "<<", "unsigned int"), ("shr", ">>", "unsigned int"),
              ("sar", ">>", "int")]
    for name, op, typ in shifts:
        for n in range(1, 16):
            w("NI static %s %s_%d(%s x) { return x %s %d; }" %
              (typ, name, n, typ, op, n))
    w("NI static int args6(int a, int b, int c, int d, int e, int f) "
      "{ return a - b + c - d + e - f; }")
    w("NI static unsigned int fib(unsigned int n) "
      "{ return n < 2 ? n : fib(n - 1) + fib(n - 2); }")
    w("NI static int vsum(int n, ...) { va_list ap; int s = 0; "
      "va_start(ap, n); while (n-- > 0) s += va_arg(ap, int); "
      "va_end(ap); return s; }")
    w("int main(void)")
    w("{")
    w("  unsigned int i, j;")
    for name, op, typ in OPS:
        w("  printf(\"rr %s\\n\");" % name)
        w("  for (i = 0; i < %d; i++) for (j = 0; j < %d; j++) "
          "out('0' + rr_%s((%s)v[i], (%s)v[j]));" %
          (len(V), len(V), name, typ, typ))
        w("  end();")
        emit("rr " + name)
        emit("".join(str(pyop(op, a, b, typ)) for a in V for b in V))
    for name, op, typ in OPS:
        w("  printf(\"rc %s\\n\");" % name)
        for k in K:
            w("  for (i = 0; i < %d; i++) out('0' + rc_%s_%04x((%s)v[i]));" %
              (len(V), name, k, typ))
        w("  end();")
        emit("rc " + name)
        emit("".join(str(pyop(op, a, k, typ)) for k in K for a in V))
    for name, op, typ in shifts:
        w("  printf(\"%s\\n\");" % name)
        for n in range(1, 16):
            w("  for (i = 0; i < %d; i++) outx((unsigned int)%s_%d((%s)v[i]));"
              % (len(V), name, n, typ))
        w("  end();")
        emit(name)
        r = []
        for n in range(1, 16):
            for x in V:
                if name == "shl":
                    y = (x << n) & 0xffff
                elif name == "shr":
                    y = x >> n
                else:
                    y = (s16(x) >> n) & 0xffff
                r.append("%04x" % y)
        emit("".join(r))
    w("  printf(\"calls %d %u %d\\n\", args6(1000, 7, -3, 25, 30000, -9), "
      "fib(15), vsum(5, 1, -2, 300, -4000, 5));")
    emit("calls %d %d %d" % (1000 - 7 - 3 - 25 + 30000 + 9,
                              610, 1 - 2 + 300 - 4000 + 5))
    w("  printf(\"DONE\\n\");")
    w("  return 0;")
    w("}")
    emit("DONE")
    open(sys.argv[1], "w").write("\n".join(c) + "\n")
    text = []
    for l in lines:
        if l.startswith(("rr ", "rc ", "shl", "shr", "sar", "calls", "DONE")) \
                and len(l) < 40:
            text.append(l)
        else:
            text.extend(l[i:i + 64] for i in range(0, len(l), 64))
    open(sys.argv[2], "w").write("\n".join(text) + "\n")


if __name__ == "__main__":
    main()
